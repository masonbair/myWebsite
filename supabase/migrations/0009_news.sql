-- An empty clean_text may be refilled because a restore leaves it empty until the raw email is cleaned again.
-- A null source_id may be set once, so held-back mail can be released to a newsletter (news_release_issue).
create function public.news_issues_guard() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.id is distinct from old.id
     or new.message_id is distinct from old.message_id
     or new.subject is distinct from old.subject
     or new.from_address is distinct from old.from_address
     or new.raw_path is distinct from old.raw_path
     or (new.source_id is distinct from old.source_id and old.source_id is not null)
     or (new.clean_text is distinct from old.clean_text and old.clean_text <> '') then
    raise exception 'issue text in news_issues never changes';
  end if;
  return new;
end;
$$;

create trigger news_issues_guard before update on public.news_issues
  for each row execute function public.news_issues_guard();

create function public.news_stories_guard() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if (pg_catalog.to_jsonb(new) - 'cluster_id') is distinct from (pg_catalog.to_jsonb(old) - 'cluster_id') then
    raise exception 'stories never change; write a new run instead';
  end if;
  if old.cluster_id is not null and new.cluster_id is distinct from old.cluster_id then
    raise exception 'a story never leaves its cluster';
  end if;
  return new;
end;
$$;

create trigger news_stories_guard before update on public.news_stories
  for each row execute function public.news_stories_guard();

create function public.news_shared_guard() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.id is distinct from old.id or new.item_id is distinct from old.item_id or new.url is distinct from old.url then
    raise exception 'a shared row never changes its item or url';
  end if;
  if old.fetched_text is not null and new.fetched_text is distinct from old.fetched_text then
    raise exception 'fetched_text never changes once filled';
  end if;
  return new;
end;
$$;

create trigger news_shared_guard before update on public.news_shared
  for each row execute function public.news_shared_guard();

-- Security definer so the owner's share can write news_shared, which authenticated has no insert grant on.
-- No exception handler: if this insert fails the share fails too, so the item and its row exist together or not at all.
create function public.news_items_share() returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  link text := substring(new.description from '(https?://[^\s<>"'']+)');
begin
  -- Trailing punctuation is the sentence's, except a ')' that closes a '(' in the link, as in Wikipedia links.
  while link ~ '[].,;:!?)}]$' loop
    exit when pg_catalog.right(link, 1) = ')'
      and pg_catalog.length(pg_catalog.replace(link, '(', '')) <= pg_catalog.length(pg_catalog.replace(link, ')', ''));
    link := pg_catalog.left(link, -1);
  end loop;
  -- A link over 2,000 characters is skipped rather than cut, since a cut link points somewhere else.
  if link ~ '^https?://.' and pg_catalog.length(link) <= 2000 then
    insert into public.news_shared (item_id, url, title) values (new.id, link, new.title);
  end if;
  return null;
end;
$$;

revoke execute on function public.news_items_share() from public, anon, authenticated, service_role;

create trigger news_items_share after insert on public.items
  for each row when (new.source = 'share')
  execute function public.news_items_share();

-- A stale claim means the worker stopped mid-row, so it counts as an attempt; the third one ends the row as failed.
create function public.news_claim(p_kind text, p_limit int, p_stale interval default '15 minutes')
returns setof uuid
language plpgsql set search_path = ''
as $$
declare
  gave_up constant text := 'the job stopped while working on this 3 times';
begin
  if p_kind = 'issue' then
    return query
      with picked as (
        select i.id, i.status = 'processing' as stale from public.news_issues i
        where i.status = 'pending'
           or (i.status = 'failed' and i.attempts < 3 and coalesce(i.next_attempt_at, now()) <= now())
           or (i.status = 'processing' and i.claimed_at < now() - p_stale)
        order by i.created_at, i.id
        limit greatest(coalesce(p_limit, 0), 0)
        for update skip locked
      ),
      claimed as (
        update public.news_issues n
        set status = case when picked.stale and n.attempts + 1 >= 3 then 'failed' else 'processing' end,
            attempts = n.attempts + picked.stale::int,
            last_error = case when picked.stale and n.attempts + 1 >= 3 then gave_up else n.last_error end,
            claimed_at = now()
        from picked where n.id = picked.id
        returning n.id, n.status
      )
      select claimed.id from claimed where claimed.status = 'processing';
  elsif p_kind = 'shared' then
    return query
      with picked as (
        select s.id, s.status = 'processing' as stale from public.news_shared s
        where s.status = 'pending'
           or (s.status = 'failed' and s.attempts < 3 and coalesce(s.next_attempt_at, now()) <= now())
           or (s.status = 'processing' and s.claimed_at < now() - p_stale)
        order by s.created_at, s.id
        limit greatest(coalesce(p_limit, 0), 0)
        for update skip locked
      ),
      claimed as (
        update public.news_shared n
        set status = case when picked.stale and n.attempts + 1 >= 3 then 'failed' else 'processing' end,
            attempts = n.attempts + picked.stale::int,
            last_error = case when picked.stale and n.attempts + 1 >= 3 then gave_up else n.last_error end,
            claimed_at = now()
        from picked where n.id = picked.id
        returning n.id, n.status
      )
      select claimed.id from claimed where claimed.status = 'processing';
  else
    raise exception 'unknown claim kind %', p_kind;
  end if;
end;
$$;

-- Security definer because the owner has no update grant; the 'role' setting names the caller here, as in items_keep_history.
create function public.news_retry(p_id uuid) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  changed int;
begin
  if pg_catalog.current_setting('role', true) is distinct from 'authenticated' or not public.is_owner() then
    return false;
  end if;
  update public.news_issues set status = 'pending', attempts = 0, next_attempt_at = null
  where id = p_id and status = 'failed';
  get diagnostics changed = row_count;
  if changed = 0 then
    update public.news_shared set status = 'pending', attempts = 0, next_attempt_at = null
    where id = p_id and status = 'failed';
    get diagnostics changed = row_count;
  end if;
  return changed > 0;
end;
$$;

-- Owner-only like news_retry. Held-back mail keeps any source it matched; one with no source takes the picked one.
create function public.news_release_issue(p_id uuid, p_source text) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  changed int;
begin
  if pg_catalog.current_setting('role', true) is distinct from 'authenticated' or not public.is_owner() then
    return false;
  end if;
  if p_source = 'shared' or not exists (select 1 from public.news_sources where id = p_source) then
    return false;
  end if;
  update public.news_issues
  set source_id = p_source, status = 'pending', attempts = 0, next_attempt_at = null, claimed_at = null
  where id = p_id and status = 'quarantined' and (source_id is null or source_id = p_source);
  get diagnostics changed = row_count;
  return changed > 0;
end;
$$;

-- Only current-run news stories from public newsletters count, so shared reads, sponsors and old runs never reach the public page.
-- Public is decided by the issue's source, which never changes, not by the source the model wrote on the story.
create function public.news_refresh_trends(p_from date, p_to date) returns void
language plpgsql set search_path = ''
as $$
begin
  if p_from is null or p_to is null or p_from > p_to then
    raise exception 'news_refresh_trends needs p_from <= p_to';
  end if;
  -- Two overlapping rebuilds would collide on the primary keys, so they take turns.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('news_refresh_trends'));

  delete from public.news_trends_daily where day between p_from and p_to;
  delete from public.news_trends_coverage where day between p_from and p_to;

  with current_stories as (
    select s.id, s.story_date, i.source_id, s.sentiment, s.cluster_id, s.topics, s.company_ids,
           coalesce(i.public_url, src.homepage) as public_url
    from public.news_stories s
    join public.news_issues i on i.id = s.issue_id and i.current_run_id = s.run_id
    join public.news_sources src on src.id = i.source_id and src.public
    where s.kind = 'news' and s.story_date between p_from and p_to
  ),
  mentions as (
    select cs.id, cs.story_date, cs.source_id, cs.sentiment, cs.cluster_id, cs.public_url,
           'topic'::text as kind, t.slug as key
    from current_stories cs
    join public.news_topics t on t.slug = any (cs.topics) and t.active
    union all
    select cs.id, cs.story_date, cs.source_id, cs.sentiment, cs.cluster_id, cs.public_url,
           'company'::text, c.id::text
    from current_stories cs
    join public.news_companies c on c.id = any (cs.company_ids)
  ),
  daily as (
    insert into public.news_trends_daily (day, kind, key, stories, mentions, tone_avg, sources)
    select story_date, kind, key,
           count(distinct coalesce('c' || cluster_id::text, 's' || id::text))::int,
           count(*)::int,
           round(avg(sentiment), 2),
           array_agg(distinct source_id order by source_id)
    from mentions
    group by story_date, kind, key
  )
  insert into public.news_trends_coverage (day, kind, key, source_id, public_url)
  select story_date, kind, key, source_id, max(public_url)
  from mentions
  group by story_date, kind, key, source_id;
end;
$$;

-- The owner's connector counts current-run news stories from issues and shared reads, grouped here so no row limit can cut them short.
create function public.news_story_counts(p_kind text, p_keys text[], p_from date, p_to date, p_bucket text)
returns table (bucket date, stories int, mentions int, tone_avg numeric)
language sql stable set search_path = ''
as $$
  select date_trunc(p_bucket, s.story_date)::date,
         count(distinct coalesce('c' || s.cluster_id::text, 's' || s.id::text))::int,
         count(*)::int,
         round(avg(s.sentiment), 2)
  from public.news_stories s
  left join public.news_issues i on i.id = s.issue_id
  left join public.news_shared sh on sh.id = s.shared_id
  where s.kind = 'news'
    and s.run_id = coalesce(i.current_run_id, sh.current_run_id)
    and s.story_date between p_from and p_to
    and p_bucket in ('day', 'week', 'month')
    and case p_kind
          when 'topic' then s.topics && p_keys
          when 'company' then s.company_ids::text[] && p_keys
          else false
        end
  group by 1
  order by 1;
$$;

-- Coverage only: a topic or company with at least 3 stories in the last p_days days and more than before is "more", the reverse is "less".
create function public.news_story_movers(p_days int, p_limit int)
returns table (kind text, key text, recent int, previous int)
language sql stable set search_path = ''
as $$
  with today as (select (now() at time zone 'utc')::date as d),
  cur as (
    select s.id, s.story_date, s.cluster_id, s.topics, s.company_ids
    from public.news_stories s
    left join public.news_issues i on i.id = s.issue_id
    left join public.news_shared sh on sh.id = s.shared_id
    where s.kind = 'news'
      and s.run_id = coalesce(i.current_run_id, sh.current_run_id)
      and s.story_date between (select d from today) - (2 * p_days - 1) and (select d from today)
  ),
  mentions as (
    select c.id, c.story_date, c.cluster_id, 'topic'::text as kind, t as key
    from cur c, unnest(c.topics) as t
    union all
    select c.id, c.story_date, c.cluster_id, 'company', co::text
    from cur c, unnest(c.company_ids) as co
  ),
  tally as (
    select m.kind, m.key,
           count(distinct coalesce('c' || m.cluster_id::text, 's' || m.id::text))
             filter (where m.story_date > (select d from today) - p_days)::int as recent,
           count(distinct coalesce('c' || m.cluster_id::text, 's' || m.id::text))
             filter (where m.story_date <= (select d from today) - p_days)::int as previous
    from mentions m
    group by m.kind, m.key
  )
  select t.kind, t.key, t.recent, t.previous
  from tally t
  where (t.recent >= 3 and t.recent > t.previous) or (t.previous >= 3 and t.recent < t.previous)
  order by abs(t.recent - t.previous) desc, t.kind, t.key
  limit least(greatest(p_limit, 1), 50);
$$;

-- Trend rows outlive a topic being switched off until the next rebuild, so switched-off topics are dropped here.
create function public.news_public_trends(p_from date, p_to date)
returns table (day date, kind text, key text, label text, ticker text, stories int, mentions int, tone_avg numeric, sources text[])
language sql stable set search_path = ''
as $$
  select d.day, d.kind, d.key,
         coalesce(t.name, c.name, d.key),
         case when c.ticker_verified then c.ticker end,
         d.stories, d.mentions, d.tone_avg, d.sources
  from public.news_trends_daily d
  left join public.news_topics t on d.kind = 'topic' and t.slug = d.key
  left join public.news_companies c on d.kind = 'company' and c.id::text = d.key
  where d.day between p_from and p_to
    and (d.kind = 'company' or t.active)
  order by d.day, d.kind, d.key;
$$;

create function public.news_public_coverage(p_kind text, p_key text, p_from date)
returns table (day date, source_name text, public_url text)
language sql stable set search_path = ''
as $$
  select v.day, src.name, v.public_url
  from public.news_trends_coverage v
  join public.news_sources src on src.id = v.source_id and src.public
  where v.kind = p_kind and v.key = p_key and v.day >= p_from
  order by v.day desc, src.name;
$$;

