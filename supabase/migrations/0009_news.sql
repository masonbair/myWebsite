-- Newsletter trends: private issues and stories for the owner, plus count-only trend tables the public page reads
-- server-side. Guards live in triggers because the service role bypasses RLS but not triggers.

create table public.news_sources (
  id text primary key check (id ~ '^[a-z0-9-]{2,40}$'),
  name text not null check (length(btrim(name)) between 1 and 100),
  sender_addresses text[] not null default '{}' check (array_position(sender_addresses, null) is null),
  sender_domains text[] not null default '{}' check (array_position(sender_domains, null) is null),
  homepage text check (homepage ~ '^https://[^\s?#"''<>]+$'),
  -- Filled with {yyyy}, {mm}, {dd} and {slug} by publicIssueUrl; null means the homepage stands in.
  archive_pattern text check (archive_pattern ~ '^https://[^\s?#"''<>]+$'),
  public boolean not null default true,
  active boolean not null default true
);

