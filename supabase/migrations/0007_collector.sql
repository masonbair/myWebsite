-- The phone retries after any failure, so a repeat of a row already stored is a no-op rather than an error.
create function public.collector_add_photo(p_path text, p_asset_id text, p_taken_at timestamptz, p_width integer, p_height integer)
returns void
language plpgsql security invoker set search_path = ''
as $$
begin
  if not public.is_owner() then
    raise exception 'only the owner can add a photo' using errcode = '42501';
  end if;
  insert into public.collector_photo (path, asset_id, taken_at, width, height)
  values (p_path, p_asset_id, p_taken_at, p_width, p_height)
  on conflict do nothing;
end;
$$;

create function public.collector_add_daylio_export(p_path text, p_filename text, p_size_bytes bigint, p_modified_at timestamptz)
