-- The Collector phone app: a private place may arrive with no city, plus photo, Daylio export and heartbeat records.
-- Contract: shared/collector-contract.ts. No coordinate columns on purpose; the phone never sends any.

-- Inside a private place the phone sends region and country only, so the city may be missing there and nowhere else.
alter table public.now_place alter column city drop not null;
alter table public.now_place drop constraint now_place_city_check;
-- Spelled out so a null city can never turn the check into NULL, which Postgres would accept.
alter table public.now_place add constraint now_place_city_check check (
  (city is null and private) or (city is not null and length(btrim(city)) between 1 and 100)
);

create table public.collector_photo (
  id bigint generated by default as identity primary key,
  -- One object per asset, so a photo row always names the file it stands for.
  path text not null unique check (path = 'collector/' || asset_id || '.jpg'),
  asset_id text not null unique check (asset_id ~ '^[A-Za-z0-9_-]{1,200}$'),
  taken_at timestamptz not null,
  width integer not null check (width between 1 and 100000),
  height integer not null check (height between 1 and 100000),
  hidden boolean not null default false,
  created_at timestamptz not null default now()
);

create index collector_photo_taken_at_idx on public.collector_photo (taken_at desc, id desc);

create table public.collector_daylio_export (
  id bigint generated by default as identity primary key,
  path text not null unique,
  filename text not null check (length(btrim(filename)) between 1 and 255),
  size_bytes bigint not null check (size_bytes >= 0),
  modified_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (filename, size_bytes, modified_at),
  -- Same as daylioPath in shared/collector-contract.ts: each version of a re-exported file gets its own object.
  constraint collector_daylio_export_path_check check (
    path ~ '^exports/[0-9]+-[0-9]+-[A-Za-z0-9._-]{1,200}$' and position('..' in path) = 0
    and starts_with(path, 'exports/' || floor(extract(epoch from modified_at) * 1000)::bigint || '-' || size_bytes || '-')
  )
);

-- Exactly { at, items: [{ key, ok }] }, so a heartbeat can never carry anything else, a place or a coordinate included.
create function public.collector_heartbeat_status_ok(s jsonb) returns boolean
language plpgsql immutable set search_path = ''
as $$
declare
  item jsonb;
begin
  if jsonb_typeof(s) is distinct from 'object'
     or (select array_agg(k order by k) from jsonb_object_keys(s) k) is distinct from array['at', 'items']
     or jsonb_typeof(s -> 'at') <> 'string'
     or (s ->> 'at') !~ '^\d{4}-\d{2}-\d{2}T[0-9:.]{5,18}(Z|[+-]\d{2}:\d{2})$'
     or jsonb_typeof(s -> 'items') <> 'array'
     or jsonb_array_length(s -> 'items') > 50 then
    return false;
  end if;
  for item in select jsonb_array_elements(s -> 'items') loop
    if jsonb_typeof(item) <> 'object'
       or (select array_agg(k order by k) from jsonb_object_keys(item) k) is distinct from array['key', 'ok']
       or jsonb_typeof(item -> 'key') <> 'string'
       or (item ->> 'key') !~ '^[a-z0-9:_-]{1,40}$'
       or jsonb_typeof(item -> 'ok') <> 'boolean' then
      return false;
    end if;
  end loop;
  return true;
end;
$$;

revoke execute on function public.collector_heartbeat_status_ok(jsonb) from public, anon;
grant execute on function public.collector_heartbeat_status_ok(jsonb) to authenticated, service_role;

create table public.collector_heartbeat (
  id bigint generated by default as identity primary key,
  status jsonb not null check (public.collector_heartbeat_status_ok(status)),
  created_at timestamptz not null default now()
);

create index collector_heartbeat_created_at_idx on public.collector_heartbeat (created_at desc, id desc);

-- Hiding is the only edit: the service role skips RLS, so this trigger is what keeps every other column fixed.
create function public.collector_photo_only_hidden_changes() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if (new.id, new.path, new.asset_id, new.taken_at, new.width, new.height, new.created_at)
     is distinct from (old.id, old.path, old.asset_id, old.taken_at, old.width, old.height, old.created_at) then
    raise exception 'only hidden can change on a collector photo';
  end if;
  return new;
end;
$$;

create trigger collector_photo_only_hidden_changes before update on public.collector_photo
  for each row execute function public.collector_photo_only_hidden_changes();
