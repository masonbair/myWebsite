-- Security definer because Mason's session has no update or select grant on collector_photo; returns false when no photo matched.
create function public.collector_set_photo_hidden(p_asset_id text, p_hidden boolean)
returns boolean
language plpgsql security definer set search_path = ''
as $$
begin
  if p_hidden is null then
    raise exception 'p_hidden must be true or false' using errcode = '22004';
  end if;
  if not public.is_owner() then
    raise exception 'only the owner can hide a photo' using errcode = '42501';
  end if;
  update public.collector_photo set hidden = p_hidden where asset_id = p_asset_id;
  return found;
end;
$$;

