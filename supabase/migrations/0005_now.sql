-- The public board's place and last bake. Rows are only ever added: the newest place row and the latest bake win.
-- No coordinate columns on purpose; only the server reads these tables, through the service role.

create table public.now_place (
  id bigint generated by default as identity primary key,
  city text not null check (length(btrim(city)) between 1 and 100),
  region text not null default '' check (length(region) <= 100),
  country text not null check (length(btrim(country)) between 1 and 100),
  private boolean not null default false,
  -- The phone's IANA zone (never coordinates), so reminders follow Mason; null when the phone sent none.
  time_zone text check (length(time_zone) <= 64),
  updated_at timestamptz not null default now()
);

create table public.now_bake (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  -- Same rule as PHOTO_SRC in lib/now.ts: only a file under /misc, never a URL.
  photo text check (photo ~ '^/misc/[A-Za-z0-9._-]+\.(webp|jpe?g|png)$' and position('..' in photo) = 0),
  baked_at timestamptz not null default now()
);

-- Privacy belongs to the place, not one ping: the phone writes private = false, so a fresh ping from a private place must stay private.
create table public.now_place_privacy (
  id bigint generated by default as identity primary key,
  city text not null check (length(btrim(city)) between 1 and 100),
  region text not null default '' check (length(region) <= 100),
  country text not null check (length(btrim(country)) between 1 and 100),
  private boolean not null,
  created_at timestamptz not null default now()
);

-- Place names are matched loosely so a spelling difference from the phone can never make a private place public.
create function public.now_norm_text(p text) returns text
language sql immutable set search_path = ''
as $$ select lower(regexp_replace(btrim(coalesce(p, '')), '\s+', ' ', 'g')) $$;

