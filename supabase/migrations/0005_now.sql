-- The public board's place and last bake. Rows are only ever added: the newest place row and the latest bake win.
-- No coordinate columns on purpose; only the server reads these tables, through the service role.

create table public.now_place (
  id bigint generated by default as identity primary key,
  city text not null check (length(btrim(city)) between 1 and 100),
  region text not null default '' check (length(region) <= 100),
  country text not null check (length(btrim(country)) between 1 and 100),
  private boolean not null default false,
  updated_at timestamptz not null default now()
);

create table public.now_bake (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  -- Same rule as PHOTO_SRC in lib/now.ts: only a file under /misc, never a URL.
  photo text check (photo ~ '^/misc/[A-Za-z0-9._-]+\.(webp|jpe?g|png)$' and position('..' in photo) = 0),
  baked_at timestamptz not null default now()
);

-- Privacy belongs to the place, not one ping: the phone writes private = false, so a fresh ping from a private place must stay private.
create table public.now_place_privacy (
  id bigint generated by default as identity primary key,
  city text not null check (length(btrim(city)) between 1 and 100),
  region text not null default '' check (length(region) <= 100),
  country text not null check (length(btrim(country)) between 1 and 100),
  private boolean not null,
  created_at timestamptz not null default now()
);

create index now_place_privacy_place_idx on public.now_place_privacy (lower(city), lower(region), lower(country), id desc);

create index now_bake_baked_at_idx on public.now_bake (baked_at desc, id desc);

create trigger now_place_no_delete before delete on public.now_place
  for each row execute function public.hub_no_delete();
create trigger now_bake_no_delete before delete on public.now_bake
  for each row execute function public.hub_no_delete();
create trigger now_place_privacy_no_delete before delete on public.now_place_privacy
  for each row execute function public.hub_no_delete();
create trigger now_place_privacy_no_truncate before truncate on public.now_place_privacy
  for each statement execute function public.hub_no_delete();
create trigger now_place_no_truncate before truncate on public.now_place
  for each statement execute function public.hub_no_delete();
create trigger now_bake_no_truncate before truncate on public.now_bake
  for each statement execute function public.hub_no_delete();

alter table public.now_place enable row level security;
alter table public.now_bake enable row level security;
alter table public.now_place_privacy enable row level security;

create policy now_place_owner_insert on public.now_place
  for insert to authenticated with check (public.is_owner());
create policy now_bake_owner_insert on public.now_bake
  for insert to authenticated with check (public.is_owner());
create policy now_place_privacy_owner_insert on public.now_place_privacy
  for insert to authenticated with check (public.is_owner());

-- Insert only: marking a place private or public adds a privacy row, so history is never edited.
revoke all on table public.now_place, public.now_bake, public.now_place_privacy from anon, authenticated;
revoke all on sequence public.now_place_id_seq, public.now_bake_id_seq, public.now_place_privacy_id_seq from anon, authenticated;
grant insert on table public.now_place, public.now_bake, public.now_place_privacy to authenticated;

-- The newest place with its effective privacy: its own flag, or the newest privacy row for the same place (ignoring case).
create function public.now_current_place()
returns table (city text, region text, country text, private boolean, sent_private boolean, updated_at timestamptz)
language sql stable set search_path = ''
as $$
  select p.city, p.region, p.country,
         p.private or coalesce((
           select v.private from public.now_place_privacy v
           where lower(v.city) = lower(p.city) and lower(v.region) = lower(p.region) and lower(v.country) = lower(p.country)
           order by v.id desc
           limit 1
         ), false),
         p.private,
         p.updated_at
  from public.now_place p
  order by p.id desc
  limit 1;
$$;

revoke execute on function public.now_current_place() from public, anon, authenticated;
grant execute on function public.now_current_place() to service_role;
